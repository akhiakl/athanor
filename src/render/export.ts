// Export serializers, spec 3.4: SVG as streamed chunks and PNG through a scaled canvas. They read the committed log, so exporting a large
// drawing runs in the render worker and never blocks drawing. shortcut: no baked-base image (there is no baking yet, 2.7) and no PDF
// writer (session recording lands with pages, section 8.4).
import { CLOSE, CUBIC, F_EVENODD, F_FILL, F_GRADIENT, H, LINE, MOVE, QUAD } from '../core/arena';
import type { Shape } from './batch';
import type { Entry } from './committed';
import { drawShape, type Ctx2D } from './draw';

export interface ExportOptions {
  width: number;
  height: number;
  /** CSS colour of the page background. */
  background: string;
  /** Omit the background (PNG keeps alpha, SVG drops the rect). */
  transparent: boolean;
}

/** Safari's canvas area limit, spec 3.4.2. */
export const MAX_PIXELS = 16.7e6;

/** Largest of 1..4 whose output stays under the canvas area limit. */
export const maxScale = (w: number, h: number): number => Math.max(1, Math.min(4, Math.floor(Math.sqrt(MAX_PIXELS / Math.max(1, w * h)))));

/** Two decimals, trailing zeros trimmed, no "-0". */
export const num = (v: number): string => {
  const r = Math.round(v * 100) / 100;
  return r === 0 ? '0' : String(r);
};

const hex2 = (n: number): string => (n < 16 ? '0' : '') + n.toString(16);
const colour = (rgba: number): string => {
  const u = rgba >>> 0;
  return `#${hex2(u >>> 24)}${hex2((u >>> 16) & 255)}${hex2((u >>> 8) & 255)}`;
};
const alpha = (rgba: number): string => num((rgba & 255) / 255);

/** Path data from a command stream (M, L, Q, C, Z), spec 3.4.1. */
export function pathData(s: Shape): string {
  let d = '';
  let v = 0;
  for (let i = 0; i < s.cmd.length; i++) {
    switch (s.cmd[i]) {
      case MOVE: d += `M${num(s.vtx[v])} ${num(s.vtx[v + 1])}`; v += 2; break;
      case LINE: d += `L${num(s.vtx[v])} ${num(s.vtx[v + 1])}`; v += 2; break;
      case QUAD: d += `Q${num(s.vtx[v])} ${num(s.vtx[v + 1])} ${num(s.vtx[v + 2])} ${num(s.vtx[v + 3])}`; v += 4; break;
      case CUBIC: d += `C${num(s.vtx[v])} ${num(s.vtx[v + 1])} ${num(s.vtx[v + 2])} ${num(s.vtx[v + 3])} ${num(s.vtx[v + 4])} ${num(s.vtx[v + 5])}`; v += 6; break;
      case CLOSE: d += 'Z'; break;
    }
  }
  return d;
}

const CHUNK = 64 * 1024;

/**
 * The SVG document as string chunks of at most ~64 KB (joined by the Blob constructor, never one giant string).
 * Gradient records get a linearGradient in <defs>, in the same two-stop form the canvas draws.
 */
export function svgChunks(entries: readonly Entry[], o: ExportOptions): string[] {
  const chunks: string[] = [];
  let buf = '';
  const out = (s: string): void => {
    buf += s;
    if (buf.length >= CHUNK) {
      chunks.push(buf);
      buf = '';
    }
  };
  const W = num(o.width), H_ = num(o.height);
  out(`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H_}" viewBox="0 0 ${W} ${H_}">\n<!-- Generated by Athanor -->\n`);
  if (!o.transparent) out(`<rect width="100%" height="100%" fill="${o.background}"/>\n`);

  const live = entries.filter((e) => e.alive);
  const grads = new Map<Entry, string>();
  let defs = '';
  for (const e of live) {
    const { hdr, hdrF } = e.shape;
    if (!(hdr[H.FLAGS] & F_GRADIENT)) continue;
    const x1 = hdrF[H.GX1], y1 = hdrF[H.GY1], x2 = hdrF[H.GX2], y2 = hdrF[H.GY2];
    if (x1 === x2 && y1 === y2) continue; // degenerate: the canvas keeps the solid colour, so does the export
    const id = `g${grads.size}`;
    grads.set(e, id);
    const c1 = hdr[H.RGBA], c2 = hdr[H.GRADIENT_RGBA2];
    defs += `<linearGradient id="${id}" gradientUnits="userSpaceOnUse" x1="${num(x1)}" y1="${num(y1)}" x2="${num(x2)}" y2="${num(y2)}" spreadMethod="pad">`
      + `<stop offset="0" stop-color="${colour(c1)}" stop-opacity="${alpha(c1)}"/><stop offset="1" stop-color="${colour(c2)}" stop-opacity="${alpha(c2)}"/></linearGradient>\n`;
  }
  if (defs) out(`<defs>\n${defs}</defs>\n`);

  for (const e of live) {
    const { hdr, hdrF } = e.shape;
    const rgba = hdr[H.RGBA];
    const flags = hdr[H.FLAGS];
    const grad = grads.get(e);
    const paint = grad ? `url(#${grad})` : colour(rgba);
    const op = grad ? '' : ` ${flags & F_FILL ? 'fill' : 'stroke'}-opacity="${alpha(rgba)}"`;
    if (flags & F_FILL) out(`<path d="${pathData(e.shape)}" fill="${paint}"${op} fill-rule="${flags & F_EVENODD ? 'evenodd' : 'nonzero'}"/>\n`);
    else out(`<path d="${pathData(e.shape)}" fill="none" stroke="${paint}"${op} stroke-width="${num(hdrF[H.LINE_WIDTH])}" stroke-linecap="round" stroke-linejoin="bevel"/>\n`);
  }
  out('</svg>\n');
  if (buf) chunks.push(buf);
  return chunks;
}

export const svgBlob = (entries: readonly Entry[], o: ExportOptions): Blob => new Blob(svgChunks(entries, o), { type: 'image/svg+xml' });

/** The slice of OffscreenCanvas the PNG export needs. */
export interface ExportCanvas {
  getContext(type: '2d'): (Ctx2D & { setTransform(a: number, b: number, c: number, d: number, e: number, f: number): void }) | null;
  convertToBlob(opts?: { type?: string }): Promise<Blob>;
}
export type MakeCanvas = (w: number, h: number) => ExportCanvas;

/**
 * PNG at `scale` (clamped to the canvas area limit): replays the log into a fresh canvas at scale, spec 3.4.2.
 * A transparent export skips the background fill so the alpha channel survives.
 */
export async function pngBlob(entries: readonly Entry[], o: ExportOptions, scale: number, make: MakeCanvas): Promise<Blob> {
  const k = Math.min(Math.max(1, Math.round(scale)), maxScale(o.width, o.height));
  const canvas = make(Math.round(o.width * k), Math.round(o.height * k));
  const ctx = canvas.getContext('2d');
  if (!ctx) throw new Error('2d context unavailable');
  ctx.setTransform(k, 0, 0, k, 0, 0);
  if (!o.transparent) {
    ctx.fillStyle = o.background;
    ctx.fillRect(0, 0, o.width, o.height);
  }
  for (const e of entries) if (e.alive) drawShape(ctx, e.shape);
  return canvas.convertToBlob({ type: 'image/png' });
}

/** A small preview of the page for the file browser: `width` px wide, always on the page background, WebP where the browser can encode it. */
export async function thumbBlob(entries: readonly Entry[], o: ExportOptions, width: number, make: MakeCanvas): Promise<Blob> {
  const k = Math.min(1, Math.max(0.01, width / Math.max(1, o.width)));
  const canvas = make(Math.max(1, Math.round(o.width * k)), Math.max(1, Math.round(o.height * k)));
  const ctx = canvas.getContext('2d');
  if (!ctx) throw new Error('2d context unavailable');
  ctx.setTransform(k, 0, 0, k, 0, 0);
  ctx.fillStyle = o.background;
  ctx.fillRect(0, 0, o.width, o.height);
  for (const e of entries) if (e.alive) drawShape(ctx, e.shape);
  return canvas.convertToBlob({ type: 'image/webp' }); // Safari cannot encode WebP and returns a PNG: still a valid image
}
